# Handling Missing Values in a Dataset in Feature Engineering

# Handling missing values is an important step in feature engineering, as missing data can lead to biased estimates and reduced model performance. There are several techniques to handle missing values, including:

# 1. Removing rows with missing values
# 2. Imputing missing values with mean, median, or mode
# 3. Using advanced imputation techniques like KNN or MICE

# 4. Using domain knowledge to fill in missing values

# Numerical: Normally distributed data - mean, skewed data - media
# Categorical: mode, "Missing" or "Unknown" category